create extension if not exists pgcrypto;

-- Admin allow-list: only Auth users listed here can administer the site.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

drop policy if exists "Admins can read their own admin record" on public.admin_users;
create policy "Admins can read their own admin record"
on public.admin_users for select to authenticated
using (auth.uid() = user_id);

-- Products
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  image_url text,
  emoji text default '▦',
  note text,
  featured boolean not null default false,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.products enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
on public.products for select to anon, authenticated using (is_active = true);

drop policy if exists "Admins can read all products" on public.products;
create policy "Admins can read all products"
on public.products for select to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products"
on public.products for insert to authenticated
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products"
on public.products for update to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
on public.products for delete to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

-- Inquiries, request-call forms and product order requests
create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  inquiry_type text not null default 'General Inquiry',
  customer_name text not null,
  phone text not null,
  product_name text,
  requirement text,
  address text,
  status text not null default 'New' check (status in ('New','Contacted','Completed')),
  created_at timestamptz not null default now()
);
alter table public.inquiries enable row level security;

drop policy if exists "Anyone can submit an inquiry" on public.inquiries;
create policy "Anyone can submit an inquiry"
on public.inquiries for insert to anon, authenticated
with check (
  length(trim(customer_name)) between 1 and 120
  and phone ~ '^[0-9+() -]{8,20}$'
  and length(trim(inquiry_type)) between 1 and 60
);

